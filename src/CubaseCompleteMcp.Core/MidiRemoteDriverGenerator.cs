        unique_id: root.getObjectUniqueIDString(runtime.mapping, objectId),
        title: root.getObjectTitle(runtime.mapping, objectId),
        type: root.getObjectTypeName ? root.getObjectTypeName(runtime.mapping, objectId) : null,
