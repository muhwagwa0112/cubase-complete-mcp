public sealed class MidiRemoteDriverGenerator
{
    public const string DriverFileName = "CBMCP_CompleteBridge.js";
    public const string CatalogFileName = "command_catalog.json";

    private static readonly JsonSerializerOptions ManifestJsonOptions = new(JsonSerializerDefaults.Web)
    {
        WriteIndented = true,
        Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping
    };

    public DriverGenerationResult Generate(KeyCommandCatalog catalog, string outputDirectory)
    {
        ArgumentNullException.ThrowIfNull(catalog);
        ArgumentException.ThrowIfNullOrWhiteSpace(outputDirectory);
        Directory.CreateDirectory(outputDirectory);

        var driverPath = Path.Combine(outputDirectory, DriverFileName);
        var catalogPath = Path.Combine(outputDirectory, CatalogFileName);
        var script = BuildScript(catalog);
        File.WriteAllText(driverPath, script, new UTF8Encoding(false));

        var manifest = new
        {
            schema_version = 1,
            protocol_version = 2,
            vendor = CubaseConstants.DeviceVendor,
            device = CubaseConstants.DeviceName,
            input_port = CubaseConstants.InputPortName,
            output_port = CubaseConstants.OutputPortName,
            command_count = catalog.Commands.Count,
            category_count = catalog.CategoryCount,
            commands = catalog.Commands.Select(command => new
            {
                id = command.Id,
                category = command.Category,
                name = command.Name,
                index = command.Index
            })
        };
        File.WriteAllText(catalogPath, JsonSerializer.Serialize(manifest, ManifestJsonOptions), new UTF8Encoding(false));

        return new DriverGenerationResult(
            driverPath,
            catalogPath,
            catalog.Commands.Count,
            catalog.CategoryCount,
            HashFile(driverPath),
            HashFile(catalogPath));
    }

    public string BuildScript(KeyCommandCatalog catalog)
    {
        ArgumentNullException.ThrowIfNull(catalog);
        var builder = new StringBuilder(512 * 1024);
        builder.AppendLine("// Generated by Cubase Complete MCP. Do not edit by hand.");
        builder.AppendLine("// ECMAScript 5 for Steinberg MIDI Remote API v1, protocol v2.");
        builder.AppendLine("'use strict';");
        builder.AppendLine("var midiremote_api = require('midiremote_api_v1');");
        builder.AppendLine();
        builder.AppendLine("var DRIVER_VERSION = '0.1.0';");
        builder.AppendLine("var PROTOCOL_VERSION = 2;");
        builder.AppendLine($"var INPUT_PORT_NAME = {Js(CubaseConstants.InputPortName)};");
        builder.AppendLine($"var OUTPUT_PORT_NAME = {Js(CubaseConstants.OutputPortName)};");
        builder.AppendLine("var deviceDriver = midiremote_api.makeDeviceDriver('CBMCP', 'CompleteBridge', 'CBMCP');");
        builder.AppendLine("var midiInput = deviceDriver.mPorts.makeMidiInput('Cubase Complete MCP Command Input');");
        builder.AppendLine("var midiOutput = deviceDriver.mPorts.makeMidiOutput('Cubase Complete MCP Feedback Output');");
        builder.AppendLine("var detection = deviceDriver.makeDetectionUnit();");
        builder.AppendLine("var portPair = detection.detectPortPair(midiInput, midiOutput);");
        builder.AppendLine("portPair.expectInputNameEquals(INPUT_PORT_NAME);");
        builder.AppendLine("portPair.expectOutputNameEquals(OUTPUT_PORT_NAME);");
        builder.AppendLine("if (detection.mPlatformFilter && detection.mPlatformFilter.expectPlatformWindows) { detection.mPlatformFilter.expectPlatformWindows(); }");
        builder.AppendLine();
        builder.Append(ProtocolRuntimeSource);
        builder.AppendLine();
        builder.Append(HostMappingPreamble);

        foreach (var command in catalog.Commands)
        {
            builder.Append("registerCommand(")
                .Append(Js(command.Id)).Append(", ")
                .Append(Js(command.Category)).Append(", ")
                .Append(Js(command.Name)).AppendLine(");");
        }

        builder.AppendLine();
        builder.Append(HostMappingCallbacksAndDispatch);
        return builder.ToString();
    }

    private static string HashFile(string path) =>
        Convert.ToHexString(System.Security.Cryptography.SHA256.HashData(File.ReadAllBytes(path))).ToLowerInvariant();

    private static string Js(string value) => JsonSerializer.Serialize(value);

