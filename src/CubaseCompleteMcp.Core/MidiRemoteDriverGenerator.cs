function codedError(code, message, details) { var error = new Error(message); error.code = code; error.details = details || {}; return error; }

function makeSessionId() {
    var value = ((new Date().getTime()) + Math.floor(Math.random() * 4294967295)) % 4294967295;
    return value === 0 ? 1 : value;
}
function nextSequence() { runtime.sequence = (runtime.sequence + 1) % 4294967296; return runtime.sequence; }
function pushUIntBE(out, value, width) {
    var i;
    value = Math.floor(Math.max(0, value));
    for (i = width - 1; i >= 0; i -= 1) { out.push(Math.floor(value / Math.pow(256, i)) % 256); }
}
function readUIntBE(bytes, offset, width) {
    var value = 0, i;
    for (i = 0; i < width; i += 1) { value = value * 256 + bytes[offset + i]; }
    return value;
}
function utf8Encode(text) {
    var out = [], i, code, next;
    for (i = 0; i < text.length; i += 1) {
        code = text.charCodeAt(i);
        if (code >= 0xD800 && code <= 0xDBFF && i + 1 < text.length) {
            next = text.charCodeAt(i + 1);
            if (next >= 0xDC00 && next <= 0xDFFF) { code = 0x10000 + ((code - 0xD800) << 10) + (next - 0xDC00); i += 1; }
        }
        if (code < 0x80) { out.push(code); }
        else if (code < 0x800) { out.push(0xC0 | (code >> 6)); out.push(0x80 | (code & 0x3F)); }
        else if (code < 0x10000) { out.push(0xE0 | (code >> 12)); out.push(0x80 | ((code >> 6) & 0x3F)); out.push(0x80 | (code & 0x3F)); }
        else { out.push(0xF0 | (code >> 18)); out.push(0x80 | ((code >> 12) & 0x3F)); out.push(0x80 | ((code >> 6) & 0x3F)); out.push(0x80 | (code & 0x3F)); }
    }
    return out;
}
function utf8Decode(bytes) {
    var out = '', i = 0, code, extra;
    while (i < bytes.length) {
        code = bytes[i++];
        if (code < 0x80) { out += String.fromCharCode(code); }
        else if ((code & 0xE0) === 0xC0 && i < bytes.length) { code = ((code & 0x1F) << 6) | (bytes[i++] & 0x3F); out += String.fromCharCode(code); }
        else if ((code & 0xF0) === 0xE0 && i + 1 < bytes.length) { code = ((code & 0x0F) << 12) | ((bytes[i] & 0x3F) << 6) | (bytes[i + 1] & 0x3F); i += 2; out += String.fromCharCode(code); }
        else if ((code & 0xF8) === 0xF0 && i + 2 < bytes.length) { code = ((code & 7) << 18) | ((bytes[i] & 0x3F) << 12) | ((bytes[i + 1] & 0x3F) << 6) | (bytes[i + 2] & 0x3F); i += 3; extra = code - 0x10000; out += String.fromCharCode(0xD800 | (extra >> 10)); out += String.fromCharCode(0xDC00 | (extra & 0x3FF)); }
        else { throw new Error('invalid UTF-8 payload'); }
    }
    return out;
}
function pack7(bytes) {
    var out = [], offset, count, mask, i;
    for (offset = 0; offset < bytes.length; offset += 7) {
        count = Math.min(7, bytes.length - offset); mask = 0;
        for (i = 0; i < count; i += 1) { if (bytes[offset + i] & 0x80) { mask |= (1 << i); } }
        out.push(mask);
        for (i = 0; i < count; i += 1) { out.push(bytes[offset + i] & 0x7F); }
    }
    return out;
}
function unpack7(bytes) {
    var out = [], offset = 0, mask, count, i, value;
    while (offset < bytes.length) {
        mask = bytes[offset++];
        if (offset >= bytes.length) { throw new Error('invalid packed group'); }
        count = Math.min(7, bytes.length - offset);
        if ((mask >> count) !== 0) { throw new Error('packed mask exceeds group'); }
        for (i = 0; i < count; i += 1) { value = bytes[offset++]; if (value > 0x7F) { throw new Error('8-bit packed byte'); } out.push(value | (((mask >> i) & 1) << 7)); }
    }
    return out;
}
function crc32(bytes, end) {
    var crc = 0xFFFFFFFF, i, bit;
    for (i = 0; i < end; i += 1) { crc = (crc ^ bytes[i]) >>> 0; for (bit = 0; bit < 8; bit += 1) { crc = ((crc >>> 1) ^ ((crc & 1) ? 0xEDB88320 : 0)) >>> 0; } }
    return (crc ^ 0xFFFFFFFF) >>> 0;
}
function encodeChunk(kind, requestId, opcode, chunkIndex, chunkCount, bytes) {
    var raw = [0x43, 0x42, 0x32, 2, kind, 0], check, packed, wire;
    pushUIntBE(raw, runtime.sessionId, 4); pushUIntBE(raw, requestId || 0, 4); pushUIntBE(raw, nextSequence(), 4);
    pushUIntBE(raw, opcode, 2); pushUIntBE(raw, chunkIndex, 2); pushUIntBE(raw, chunkCount, 2); pushUIntBE(raw, bytes.length, 4);
    Array.prototype.push.apply(raw, bytes); check = crc32(raw, raw.length); pushUIntBE(raw, check, 4);
    packed = pack7(raw); wire = [0xF0, 0x7D, 0x43, 0x42]; Array.prototype.push.apply(wire, packed); wire.push(0xF7); return wire;
}
function sendEnvelope(kind, requestId, opcode, envelope) {
    var bytes = utf8Encode(JSON.stringify(envelope)), count, index, start, chunk;
    if (bytes.length > MAX_LOGICAL_BYTES) { throw new Error('response exceeds logical payload limit'); }
    count = Math.max(1, Math.ceil(bytes.length / CHUNK_BYTES));
    for (index = 0; index < count; index += 1) { start = index * CHUNK_BYTES; chunk = bytes.slice(start, Math.min(bytes.length, start + CHUNK_BYTES)); midiOutput.sendMidi(runtime.device, encodeChunk(kind, requestId, opcode, index, count, chunk)); }
}
function decodeChunk(message) {
    var raw, length, expected, payloadEnd, expectedCrc, actualCrc;
    if (!message || message.length < 7 || message[0] !== 0xF0 || message[1] !== 0x7D || message[2] !== 0x43 || message[3] !== 0x42 || message[message.length - 1] !== 0xF7) { throw new Error('not a CBMCP v2 SysEx frame'); }
    raw = unpack7(message.slice(4, message.length - 1));
    if (raw.length < HEADER_BYTES + CRC_BYTES || raw[0] !== 0x43 || raw[1] !== 0x42 || raw[2] !== 0x32 || raw[3] !== 2 || raw[5] !== 0) { throw new Error('invalid v2 frame header'); }
    length = readUIntBE(raw, 24, 4); expected = HEADER_BYTES + length + CRC_BYTES;
    if (raw.length !== expected) { throw new Error('frame length mismatch'); }
    payloadEnd = HEADER_BYTES + length; expectedCrc = readUIntBE(raw, payloadEnd, 4); actualCrc = crc32(raw, payloadEnd);
    if (expectedCrc !== actualCrc) { throw new Error('CRC32 mismatch'); }
    return {kind: raw[4], sessionId: readUIntBE(raw, 6, 4), requestId: readUIntBE(raw, 10, 4), sequence: readUIntBE(raw, 14, 4), opcode: readUIntBE(raw, 18, 2), chunkIndex: readUIntBE(raw, 20, 2), chunkCount: readUIntBE(raw, 22, 2), payload: raw.slice(HEADER_BYTES, payloadEnd)};
}
function acceptChunk(frame) {
    var key, pending, i, joined, name, now = new Date().getTime(), pendingCount = 0;
    for (name in runtime.pendingChunks) { if (runtime.pendingChunks.hasOwnProperty(name)) { if (now - runtime.pendingChunks[name].createdAt > PENDING_TIMEOUT_MS) { delete runtime.pendingChunks[name]; } else { pendingCount += 1; } } }
    if (frame.chunkCount < 1 || frame.chunkIndex >= frame.chunkCount) { throw new Error('invalid chunk coordinates'); }
    if (frame.chunkCount === 1) { return frame; }
    key = frame.kind + ':' + frame.sessionId + ':' + frame.requestId + ':' + frame.opcode;
    pending = runtime.pendingChunks[key];
    if (!pending) { if (pendingCount >= MAX_PENDING_REQUESTS) { throw new Error('request backpressure limit reached'); } pending = {count: frame.chunkCount, parts: [], received: 0, createdAt: now}; runtime.pendingChunks[key] = pending; }
    if (pending.count !== frame.chunkCount) { delete runtime.pendingChunks[key]; throw new Error('chunk count changed'); }
    if (!pending.parts[frame.chunkIndex]) { pending.parts[frame.chunkIndex] = frame.payload; pending.received += 1; }
    if (pending.received !== pending.count) { return null; }
    joined = [];
    for (i = 0; i < pending.count; i += 1) { if (!pending.parts[i]) { return null; } Array.prototype.push.apply(joined, pending.parts[i]); if (joined.length > MAX_LOGICAL_BYTES) { delete runtime.pendingChunks[key]; throw new Error('payload too large'); } }
    delete runtime.pendingChunks[key]; frame.payload = joined; frame.chunkIndex = 0; frame.chunkCount = 1; return frame;
}
function cacheKey(frame) { return frame ? frame.sessionId + ':' + frame.requestId : ''; }
function payloadDigest(frame) { return frame && frame.payload ? frame.opcode + ':' + frame.payload.length + ':' + crc32(frame.payload, frame.payload.length) : ''; }
function remember(frame, kind, envelope) { var key = cacheKey(frame), keys, i; if (!key || !frame.payload) { return; } runtime.completed[key] = {kind: kind, envelope: envelope, digest: payloadDigest(frame), at: new Date().getTime()}; keys = Object.keys(runtime.completed); if (keys.length > REQUEST_CACHE_LIMIT) { keys.sort(function (a, b) { return runtime.completed[a].at - runtime.completed[b].at; }); for (i = 0; i < keys.length - REQUEST_CACHE_LIMIT; i += 1) { delete runtime.completed[keys[i]]; } } }
function respond(frame, data, verified) { var envelope = {ok: true, data: data || {}, verified: verified !== false, revision: runtime.revision}; remember(frame, KIND.response, envelope); sendEnvelope(KIND.response, frame.requestId, frame.opcode, envelope); }
function fail(frame, code, message, details) { var envelope = {ok: false, error: {code: code, message: message, details: details || {}}, revision: runtime.revision}; if (code !== 'REQUEST_ID_CONFLICT' && code !== 'STALE_SESSION' && code !== 'PROTOCOL_ERROR') { remember(frame, KIND.nack, envelope); } sendEnvelope(KIND.nack, frame ? frame.requestId : 0, frame ? frame.opcode : OPCODE.error, envelope); }
function emitState(key, value) { runtime.revision += 1; runtime.stateRevision[key] = runtime.revision; if (runtime.active && runtime.device) { sendEnvelope(KIND.event, 0, OPCODE['state.event'], {ok: true, data: {key: key, value: value}, verified: true, revision: runtime.revision}); } }
function hostVersion() { var value = midiremote_api.mDefaults && midiremote_api.mDefaults.mAppVersion; return value && value.getVersionString ? value.getVersionString() : ''; }

